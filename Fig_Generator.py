@dataclass
class Config:
    max_iter: int = 5000
    max_no_improve: int = 500
    time_limit: float = 300.0
    q_min: float = 0.05
    q_max: float = 0.30
    segment_length: int = 100
    rho: float = 0.10
    sigma_best: float = 3.0
    sigma_better: float = 2.0
    sigma_feasible: float = 1.0
    eps: float = 1e-7                      # penalite energetique (mines par joule)
    ls_freq: int = 1                       # 0 = pas de recherche locale
    accept: str = "sa"                     # "sa" ou "descent"
    accept_rate_init: float = 0.8
    cooling_rate: float = 0.995
