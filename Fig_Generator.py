BIG = 1e15            # cout d'un arc infaisable (jamais choisi : depasse tout budget)
INF_TIME = 1e8        # seuil M du manuscrit : tau >= M => arc infaisable
TOL = 1e-6


# ======================================================================
# CONFIGURATION
