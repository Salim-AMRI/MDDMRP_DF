# ALNS
# ======================================================================
class ALNS:
    def __init__(self, cfg: Config, seed: int):
        self.cfg = cfg
        self.rng = random.Random(seed)
        self.d_ops = list(cfg.destroy_ops)
        self.r_ops = list(cfg.repair_ops)
        self.d_w = [1.0 / len(self.d_ops)] * len(self.d_ops)
        self.r_w = [1.0 / len(self.r_ops)] * len(self.r_ops)
        self.d_theta = [0.0] * len(self.d_ops)
        self.r_theta = [0.0] * len(self.r_ops)

    def _roulette(self, weights: List[float]) -> int:
        tot = sum(weights)
        x = self.rng.random() * tot
        acc = 0.0
        for i, wt in enumerate(weights):
            acc += wt
            if x <= acc:
                return i
        return len(weights) - 1

    def _q(self, sol: Solution) -> int:
        v = sol.n_visited()
        return max(1, math.ceil(self.rng.uniform(self.cfg.q_min, self.cfg.q_max) * max(v, 1)))

    def _update_weights(self):
        cfg = self.cfg
        if not cfg.adaptive:
            self.d_theta = [0.0] * len(self.d_ops)
            self.r_theta = [0.0] * len(self.r_ops)
            return
        for w, th in ((self.d_w, self.d_theta), (self.r_w, self.r_theta)):
            s = sum(th)
            if s > 0:
                for i in range(len(w)):
                    w[i] = (1 - cfg.rho) * w[i] + cfg.rho * th[i] / s
            for i in range(len(th)):
                th[i] = 0.0

    def _init_temperature(self, inst: Instance, start: Solution) -> float:
        cfg = self.cfg
        f0 = start.objective(cfg.eps)
        worse = []
        for _ in range(100):
            op = self.rng.choice(self.d_ops)
            cand = destroy(inst, start, op, self._q(start), self.rng, cfg.rand_p)
            cand = repair(inst, cand, self.r_ops[0])
            f = cand.objective(cfg.eps)
            if f < f0:
                worse.append(f0 - f)
        if not worse:
            return 1.0
        return max(sum(worse) / len(worse) / math.log(1.0 / cfg.accept_rate_init), cfg.temp_floor)

    def solve(self, inst: Instance) -> Tuple[Solution, dict]:
        cfg, rng = self.cfg, self.rng
        t0 = time.time()
        deadline = t0 + cfg.time_limit
        cur = build_initial(inst, cfg.eps)
        if cfg.ls_freq > 0:
            cur = local_search(inst, cur, deadline)
        best = cur.copy()
        cur_f = best_f = cur.objective(cfg.eps)
        init_cov, init_energy = cur.cov, cur.energy
        temp = self._init_temperature(inst, cur) if cfg.accept == "sa" else 0.0
        no_imp = 0
        best_it = 0
        usage_d = [0] * len(self.d_ops)
        usage_r = [0] * len(self.r_ops)
        it = -1
        for it in range(cfg.max_iter):
            if time.time() > deadline:
                break
            di = self._roulette(self.d_w)
            ri = self._roulette(self.r_w)
            cand = destroy(inst, cur, self.d_ops[di], self._q(cur), rng, cfg.rand_p)
            cand = repair(inst, cand, self.r_ops[ri])
            if cfg.ls_freq > 0 and it % cfg.ls_freq == 0:
                cand = local_search(inst, cand, deadline)
            f = cand.objective(cfg.eps)
            if f > best_f + 1e-9:
                score = cfg.sigma_best
            elif f > cur_f + 1e-9:
                score = cfg.sigma_better
            else:
                score = cfg.sigma_feasible
            if f > cur_f + 1e-9:
                accept = True
            elif cfg.accept == "sa" and temp > 1e-12:
                accept = rng.random() < math.exp((f - cur_f) / temp)
            else:
                accept = False
            if accept:
                cur, cur_f = cand, f
            if f > best_f + 1e-9:
                best, best_f = cand.copy(), f
                best_it = it
                no_imp = 0
            else:
                no_imp += 1
            self.d_theta[di] += score
            self.r_theta[ri] += score
            usage_d[di] += 1
            usage_r[ri] += 1
            if (it + 1) % cfg.segment_length == 0:
                self._update_weights()
            if cfg.accept == "sa":
                temp = max(cfg.temp_floor, temp * cfg.cooling_rate)
            if no_imp >= cfg.max_no_improve:
                break
        stats = {
            "iterations": it + 1,
            "best_iteration": best_it,
            "time_s": time.time() - t0,
            "init_cov": init_cov,
            "init_energy": init_energy,
            "usage_destroy": dict(zip(self.d_ops, usage_d)),
            "usage_repair": dict(zip(self.r_ops, usage_r)),
            "weights_destroy": dict(zip(self.d_ops, [round(x, 4) for x in self.d_w])),
        }
        return best, stats


