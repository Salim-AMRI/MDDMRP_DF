"""
ALNS pour le MDDMRP-DF (Multi-Depot Drone Marine Routing Problem with Flexible Depots).

Ce fichier implemente l'algorithme decrit dans la Section 4 du manuscrit, avec
les precisions suivantes (a reporter dans le texte, voir README en fin de fichier) :

  * Representation : une route = liste ordonnee de CIBLES ; le depot de depart
    est delta_k (fixe) et le depot d'arrivee est le depot de cout minimal depuis
    la derniere cible. Une route vide = drone non active. Aucune route ne peut
    donc passer par un depot en cours de route (coherent avec le MILP).
  * Vitesses : l'energie du modele est separable par arc et il n'y a pas de
    contrainte de duree ; la vitesse optimale d'un arc est donc argmin_s e_ij^s
    (calculee une fois pour toutes). L'operateur "speed-reoptimisation" du
    manuscrit est de ce fait redondant et n'est pas implemente comme operateur.
  * Operateurs de destruction : random, worst-energy, cluster, current-sensitive.
  * Operateurs de reparation : greedy (ratio recompense / energie incrementale,
    meilleure insertion globale, jusqu'a epuisement) ; regret-2 (optionnel,
    NON present dans le manuscrit, desactive par defaut).
  * Recherche locale : 2-opt intra-route, relocate inter-route, exchange
    inter-route ; premiere amelioration ; critere = reduction de l'energie
    totale ; appliquee a chaque iteration (ls_freq = 1) jusqu'a un optimum
    local pour les trois voisinages.
  * Solution initiale (Algorithme 2) : cibles triees par w_j / e_bar_j,
    insertion de plus faible energie incrementale (equivaut a maximiser
    w_j - eps * delta_e), puis une recherche locale.
  * Critere d'acceptation : recuit simule (l'Algorithme 1 du manuscrit ne
    precise pas de critere d'acceptation : a ajouter dans le texte).
  * Classement aleatoire (puissance p, Ropke & Pisinger 2006) pour worst-energy
    et current-sensitive (ajout par rapport au manuscrit ; p = None => deterministe).
  * Scores 3 / 2 / 1 ; poids mis a jour tous les 100 iterations par
    w <- (1-rho) w + rho * theta_o / sum(theta) ; rho = 0.10.
  * Objectif : couverture ponderee - eps * energie (propulsion + chaleur de
    bord + penalite de profondeur + capteurs), eps = 1e-7 par joule : identique
    a l'objectif du MILP.

Chaque solution finale est verifiee par un validateur independant (matrices
brutes du JSON) avant d'etre enregistree.
"""

