CSV_FIELDS = ["seed", "coverage_pct", "coverage_weighted", "energy_J", "time_s", "active_drones",
              "mines_detected", "total_mines", "mines_pct", "all_mines", "iterations", "best_iteration"]


def run_one(task):
    path, seed, cfg, save_dir = task
    inst = load_instance(path)
    best, st = ALNS(cfg, seed).solve(inst)
    cov, en = validate(inst, best)
    total_mines = sum(1 for u in inst.targets() if inst.is_mine[u])
    detected = sum(1 for u in inst.targets() if inst.is_mine[u] and best.visited[u])
    row = {
        "seed": seed,
        "coverage_pct": 100.0 * cov / inst.total_weight,
        "coverage_weighted": cov,
        "energy_J": en,
        "time_s": st["time_s"],
        "active_drones": sum(1 for r in best.routes if r),
        "mines_detected": detected,
        "total_mines": total_mines,
        "mines_pct": (100.0 * detected / total_mines) if total_mines > 0 else "",
        "all_mines": (1 if detected == total_mines else 0) if total_mines > 0 else "",
        "iterations": st["iterations"],
        "best_iteration": st["best_iteration"],
    }
    if save_dir:
        os.makedirs(save_dir, exist_ok=True)
        name = os.path.splitext(os.path.basename(path))[0]
        with open(os.path.join(save_dir, "%s_seed%d.json" % (name, seed)), "w") as f:
            json.dump({"instance": inst.name, "seed": seed, "objective": best.objective(cfg.eps),
                       "routes": explicit_routes(best), "stats": st}, f)
    return path, row


def _read_done(csv_path: str) -> Dict[int, dict]:
    done = {}
    if os.path.exists(csv_path):
        with open(csv_path, "r", newline="") as f:
            for r in csv.DictReader(f):
                try:
                    done[int(r["seed"])] = r
                except (KeyError, ValueError):
                    pass
    return done


def run_batch(paths: List[str], runs: int, cfg: Config, out_dir: str, workers: int,
              resume: bool, save_dir: Optional[str]):
    os.makedirs(out_dir, exist_ok=True)
    tasks, csv_paths, done = [], {}, {}
    for p in paths:
        name = os.path.splitext(os.path.basename(p))[0]
        cp = os.path.join(out_dir, "alns_stats_%s.csv" % name)
        csv_paths[p] = cp
        d = _read_done(cp) if resume else {}
        done[p] = d
        if not resume or not d:
            with open(cp, "w", newline="") as f:
                csv.DictWriter(f, fieldnames=CSV_FIELDS).writeheader()
        for s in range(runs):
            if s not in d:
                tasks.append((p, s, cfg, save_dir))
    print("%d instances, %d runs a executer, %d workers" % (len(paths), len(tasks), workers), flush=True)
    t0 = time.time()
    with Pool(workers) as pool:
        for n, (p, row) in enumerate(pool.imap_unordered(run_one, tasks), 1):
            with open(csv_paths[p], "a", newline="") as f:
                csv.DictWriter(f, fieldnames=CSV_FIELDS).writerow(row)
            if n % 10 == 0 or n == len(tasks):
                print("  %d/%d runs (%.0f s)" % (n, len(tasks), time.time() - t0), flush=True)
    print("Termine en %.1f s. CSV dans %s" % (time.time() - t0, out_dir))


