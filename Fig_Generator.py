def extract_route_for_display(x, a, k, drones, N, S, nd):
    """Extrait UNE route pour l'affichage. Ignorée pour le calcul."""
    if pulp.value(a[k]) is None or pulp.value(a[k]) < 0.5:
        return []
    start = drones[k]["start_depot"]
    route = [start]
    visited = {start}
    current = start
    for _ in range(N):
        nxt = None
        for j in range(N):
            if j in visited:
                continue
            for s in range(S):
                var = x.get((current, j, s, k))
                if var is None:
                    continue
                v = pulp.value(var)
                if v is not None and v > 0.5:
                    nxt = j
                    break
            if nxt is not None:
                break
        if nxt is None:
            break
        route.append(nxt)
        visited.add(nxt)
        if nxt < nd:
            break
        current = nxt
    return route


