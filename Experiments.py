def cliffs_delta(a, b):
    a, b = np.asarray(a), np.asarray(b)
    gt = sum((x > y) for x in a for y in b)
    lt = sum((x < y) for x in a for y in b)
    return (gt - lt) / (len(a) * len(b))

def analyse(instances, metric, label):
    mat = np.array([
        [pd.read_csv(f"results_abl_small_{n}/alns_stats_{i}.csv")[metric].mean() for i in instances]
        for n in names
    ])
    chi2, p = friedmanchisquare(*mat)
    print(f"\n=== {label} ===")
    print(f"Friedman χ² = {chi2:.3f}, p = {p:.4f}")
    full = mat[0]
    pvals, deltas = [], []
    for k, name in enumerate(names[1:], 1):
        _, pw = wilcoxon(full, mat[k])
        pvals.append(pw)
        deltas.append(cliffs_delta(mat[k], full))
    reject, p_adj, _, _ = multipletests(pvals, method="holm")
    for n, pw, pa, d in zip(names[1:], pvals, p_adj, deltas):
        print(f"  {n:<14} p={pw:.4f}  p_Holm={pa:.4f}  δ={d:+.3f}")

