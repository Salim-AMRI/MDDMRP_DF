def backfit_constants(path):
    """Régression linéaire sur e_FM = (k·U³ + P_base)·τ_FM + γ·h_j."""
    d = json.load(open(path))
    speeds = d["drone_speeds"]
    em, tm = d["energy_matrices"], d["time_matrices"]
    nd = len(d["depots"])
    h = [0.0]*nd + [abs(t["z"]) for t in d["targets"]]
    gamma = d["depth_penalty"]
    n = len(h)
    M = 1e8

    X, y = [], []
    for s, U in enumerate(speeds):
        for i in range(n):
            for j in range(n):
                if i == j: continue
                tau = tm[s][i][j]
                if tau >= M/2: continue
                e = em[s][i][j] - gamma * h[j]
                X.append([U**3 * tau, tau])
                y.append(e)
    X, y = np.array(X), np.array(y)
    (k, Pb), *_ = np.linalg.lstsq(X, y, rcond=None)
    pred = X @ np.array([k, Pb])
    rmse = np.sqrt(np.mean((pred - y)**2))
    rel  = rmse / np.mean(y) * 100
    return k, Pb, rmse, rel, len(y)

