def generate_NC(src, dst):
    d = json.load(open(src))
    speeds = d["drone_speeds"]
    gamma  = d["depth_penalty"]
    nd = len(d["depots"])
    h = [0.0]*nd + [abs(t["z"]) for t in d["targets"]]
    xyz = [(p["x"], p["y"], p["z"]) for p in d["depots"]]
    xyz += [(p["x"], p["y"], p["z"]) for p in d["targets"]]
    n = len(xyz)

    tm_new, em_new = [], []
    for U in speeds:
        tm_s = [[0.0]*n for _ in range(n)]
        em_s = [[0.0]*n for _ in range(n)]
        for i in range(n):
            for j in range(n):
                if i == j:
                    continue
                dij = math.dist(xyz[i], xyz[j])
                tau = dij / U
                e   = (K_CONST*U**3 + P_BASE)*tau + gamma*h[j]
                tm_s[i][j] = tau
                em_s[i][j] = e
        tm_new.append(tm_s)
        em_new.append(em_s)

    d["time_matrices"]   = tm_new
    d["energy_matrices"] = em_new
    json.dump(d, open(dst, "w"))

