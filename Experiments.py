def replace_func(name, new_body):
    global src
    pattern = re.compile(rf"^def {re.escape(name)}\b.*?(?=^def |\Z)",
                         re.MULTILINE | re.DOTALL)
    if not pattern.search(src):
        log.append(f"[FAIL] {name} : fonction introuvable")
        return False
    src = pattern.sub(new_body.rstrip() + "\n\n\n", src, count=1)
    log.append(f"[OK]   {name} remplacée")
    return True

